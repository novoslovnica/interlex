// Свёртка ISV-диакритики к «упрощённому» написанию — то, что реально
// встречается в корпусе, когда пишут без диакритических знаков
// ("jezyk" вместо "język", "velmi" вместо "veľmi", "sut" вместо "sųt").
//
// Это НЕ новый лингвистический факт: набор пар взят из уже существующего
// lib/isv.ts::standardToSimple (шаг 2 «носовые и ять» и шаг 4 «мягкие
// согласные») — той самой функции, которой проект рендерит упрощённое
// написание в UI. Здесь она урезана до чистой посимвольной замены: без
// сжатия -yj/-ij и без перехода j→i перед гласной, потому что для
// сопоставления словоформ нужна операция, идемпотентная и одинаково
// применимая к обеим сторонам сравнения, а не полноценная транслитерация.
//
// Направление свёртки для носовых — ų/ǫ → u (как в standardToSimple и как
// в подтверждённой мейнтейнером паре u→ų из spellingVariants.ts), не → o
// (последнее — западный флейвор, см. lib/flavors.ts::generateWestFlavor;
// такие написания ловятся отдельно, через флейворные базы в
// analyzer-factory.ts, а не этой свёрткой).
const FOLD_MAP: Record<string, string> = {
    // носовые и ять
    'ě': 'e', 'Ě': 'E',
    'ę': 'e', 'Ę': 'E',
    'ǫ': 'u', 'Ǫ': 'U',
    'ų': 'u', 'Ų': 'U',
    // мягкие согласные
    'ľ': 'l', 'Ľ': 'L',
    'ť': 't', 'Ť': 'T',
    'ď': 'd', 'Ď': 'D',
    'ň': 'n', 'Ň': 'N',
    'ś': 's', 'Ś': 'S',
    'ź': 'z', 'Ź': 'Z',
    'ć': 'c', 'Ć': 'C',
    'đ': 'd', 'Đ': 'D',
    // Знаки долготы/тона из четырёхтоновой системы (lib/grammar/
    // fourTonesGenerator.ts). Хранятся в Lexeme.stem и попадают в
    // сгенерированные формы ПРЕКОМПОЗИРОВАННЫМИ символами, поэтому
    // stripCombiningAccents (снимает только U+0300..U+0311) их не убирает —
    // из-за чего стем "gråd" не сопоставлялся с корпусным "grad", а "smŕť"
    // с "smrti". Инвентарь снят с реальных данных: это ровно три символа,
    // остающиеся в 883 355 сгенерированных формах после прочей свёртки
    // (å 10 857, ė 6 489, ŕ 5 187); ĺ добавлен как слоговой парный к ŕ.
    'å': 'a', 'Å': 'A',
    'ė': 'e', 'Ė': 'E',
    'ŕ': 'r', 'Ŕ': 'R',
    'ĺ': 'l', 'Ĺ': 'L',
    // прочие надстрочные, уже сворачивавшиеся в DbAnalyzer.normalizeForm
    'č': 'c', 'Č': 'C',
    'š': 's', 'Š': 'S',
    'ž': 'z', 'Ž': 'Z',
    'ń': 'n', 'Ń': 'N',
    'ł': 'l', 'Ł': 'L',
    'ȯ': 'o', 'Ȯ': 'O',
    'ó': 'o', 'Ó': 'O',
    'á': 'a', 'Á': 'A',
    'é': 'e', 'É': 'E',
    'í': 'i', 'Í': 'I',
    'ú': 'u', 'Ú': 'U',
    'ý': 'y', 'Ý': 'Y',
    // еры — уже вычищались в DbAnalyzer.normalizeForm
    'ъ': '', 'ь': '',
};

/**
 * Сворачивает слово к бездиакритическому виду. Идемпотентна: применение к
 * уже свёрнутой строке ничего не меняет.
 */
export function foldDiacritics(text: string): string {
    let out = '';
    for (const ch of text) {
        const folded = FOLD_MAP[ch];
        out += folded === undefined ? ch : folded;
    }
    return out;
}
