// Свёртка ISV-диакритики к «упрощённому» написанию — то, что реально
// встречается в корпусе, когда пишут без диакритических знаков
// ("jezyk" вместо "język", "velmi" вместо "veľmi", "sut" вместо "sųt").
//
// Это НЕ новый лингвистический факт: набор пар взят из уже существующего
// lib/isv.ts::standardToSimple (шаг 2 «носовые и ять» и шаг 4 «мягкие
// согласные») — той самой функции, которой проект рендерит упрощённое
// написание в UI. Здесь она урезана до чистой посимвольной замены: без
// сжатия -yj/-ij и без перехода j→i перед гласной, потому что для
// сопоставления словоформ нужна операция, идемпотентная и одинаково
// применимая к обеим сторонам сравнения, а не полноценная транслитерация.
//
// Направление свёртки для носовых — ų/ǫ → u (как в standardToSimple и как
// в подтверждённой мейнтейнером паре u→ų из spellingVariants.ts), не → o
// (последнее — западный флейвор, см. lib/flavors.ts::generateWestFlavor;
// такие написания ловятся отдельно, через флейворные базы в
// analyzer-factory.ts, а не этой свёрткой).
const FOLD_MAP: Record<string, string> = {
    // носовые и ять
    'ě': 'e', 'Ě': 'E',
    'ę': 'e', 'Ę': 'E',
    'ǫ': 'u', 'Ǫ': 'U',
    'ų': 'u', 'Ų': 'U',
    // мягкие согласные (перед гласной заднего ряда см. SOFT_WITH_J ниже)
    'ľ': 'l', 'Ľ': 'L',
    'ť': 't', 'Ť': 'T',
    'ď': 'd', 'Ď': 'D',
    'ň': 'n', 'Ň': 'N',
    'ś': 's', 'Ś': 'S',
    'ź': 'z', 'Ź': 'Z',
    'ć': 'c', 'Ć': 'C',
    // đ и dž — одна буква в двух орфографиях (medža = medja = međa), и в
    // словаре пара пишется dž/dz (medza/medž, čudzy/čudž — 123 лексемы),
    // поэтому đ сворачивается туда же, куда dž (ž→z), а не в голое d:
    // иначе стем "međuslovjańsk" давал "medu...", а корпусное
    // "medžuslovjanskogo" — "medzu...", и слово не находилось совсем
    // (18 228 токенов medžu- против 51 с голым medu-).
    'đ': 'dz', 'Đ': 'Dz',
    // Знаки долготы/тона из четырёхтоновой системы (lib/grammar/
    // fourTonesGenerator.ts). Хранятся в Lexeme.stem и попадают в
    // сгенерированные формы ПРЕКОМПОЗИРОВАННЫМИ символами, поэтому
    // stripCombiningAccents (снимает только U+0300..U+0311) их не убирает —
    // из-за чего стем "gråd" не сопоставлялся с корпусным "grad", а "smŕť"
    // с "smrti". Инвентарь снят с реальных данных: это ровно три символа,
    // остающиеся в 883 355 сгенерированных формах после прочей свёртки
    // (å 10 857, ė 6 489, ŕ 5 187); ĺ добавлен как слоговой парный к ŕ.
    'å': 'a', 'Å': 'A',
    'ė': 'e', 'Ė': 'E',
    'ŕ': 'r', 'Ŕ': 'R',
    'ĺ': 'l', 'Ĺ': 'L',
    // прочие надстрочные, уже сворачивавшиеся в DbAnalyzer.normalizeForm
    'č': 'c', 'Č': 'C',
    'š': 's', 'Š': 'S',
    'ž': 'z', 'Ž': 'Z',
    'ń': 'n', 'Ń': 'N',
    'ł': 'l', 'Ł': 'L',
    'ȯ': 'o', 'Ȯ': 'O',
    'ó': 'o', 'Ó': 'O',
    'á': 'a', 'Á': 'A',
    'é': 'e', 'É': 'E',
    'í': 'i', 'Í': 'I',
    'ú': 'u', 'Ú': 'U',
    'ý': 'y', 'Ý': 'Y',
    // еры — уже вычищались в DbAnalyzer.normalizeForm
    'ъ': '', 'ь': '',
};

// Мягкая согласная перед гласной заднего ряда в упрощённом письме пишется
// через j: движок порождает "stolěťa", а в корпусе это "stoletja" (915
// вхождений одной только этой формы), "końa" — это "konja". Когда ť
// сворачивалась в голое t, получалось "stoleta", и форма не находилась.
// Перед e/i/ě/ę j не пишется — та же граница, что у normalizeSoftConsonants
// в lib/isv.ts. ć и đ сюда не входят: в упрощённом письме это č и dž, без j.
const SOFT_WITH_J: Record<string, string> = {
    'ľ': 'lj', 'Ľ': 'Lj',
    'ť': 'tj', 'Ť': 'Tj',
    'ď': 'dj', 'Ď': 'Dj',
    'ň': 'nj', 'Ň': 'Nj',
    'ń': 'nj', 'Ń': 'Nj',
    'ś': 'sj', 'Ś': 'Sj',
    'ź': 'zj', 'Ź': 'Zj',
};

function foldChar(ch: string): string {
    if (ch.charCodeAt(0) < 128) return ch;
    const mapped = FOLD_MAP[ch];
    if (mapped !== undefined) return mapped;
    // Тоновые знаки, которых нет в таблице (ò, è, ȁ, ȍ...), приходят из
    // текстов с разметкой ударения: "tògda" — 799 вхождений, "kògda" — 562.
    // Снимается любой комбинирующий знак, но только у латинской буквы:
    // у кириллической "й" бреве — часть самой буквы.
    const decomposed = ch.normalize('NFD');
    if (decomposed.length > 1 && /[A-Za-z]/.test(decomposed[0])) return decomposed[0];
    return ch;
}

/**
 * Сворачивает слово к бездиакритическому виду. Идемпотентна: применение к
 * уже свёрнутой строке ничего не меняет.
 */
export function foldDiacritics(text: string): string {
    // NFC: гравис может прийти и прекомпозированным "ò", и парой "o" + U+0300.
    const chars = [...text.normalize('NFC')];
    let out = '';
    for (let i = 0; i < chars.length; i++) {
        const withJ = SOFT_WITH_J[chars[i]];
        if (withJ !== undefined) {
            const next = i + 1 < chars.length ? foldChar(chars[i + 1]).toLowerCase() : '';
            out += /^[aouy]/.test(next) ? withJ : withJ[0];
            continue;
        }
        out += foldChar(chars[i]);
    }
    return out;
}
