// Транслитерация ПАЛЕОГРАФИЧЕСКОЙ кириллицы исторических корпусов (старослав.,
// др.-вост.-слав.) в научную латиницу.
//
// Это НЕ то же самое, что lib/transliteration.ts::etymCyrToEtymLat — та функция
// рассчитана на кириллицу современного ISV (там нет ъ/ь/ѡ/ѳ/ѿ/ꙗ, потому что в
// живом межславянском еров и части историч. букв просто нет). Здесь же реальные
// рукописи/трибанки (UD_Old_East_Slavic-Birchbark, UD_Old_Church_Slavonic-PROIEL)
// используют полный палеографический набор.
//
// Результат остаётся в "нейтральной" научной нотации (ǫ/ę, ъ/ь буквально), а не
// в орфографии совр. ISV — сравнение с лексемами идёт через ветвевую регенерацию
// Lexeme.proto (см. lib/historical/branchReflex.ts), а не напрямую с ISV-текстом.

// Комбинирующее титло (число/аббревиатура) — не резолвим числовое значение,
// просто убираем сам диакритический знак и транслитерируем буквы под ним как
// обычные буквы. Осознанное упрощение для первой версии.
const COMBINING_TITLO = /҃/g

// Многосимвольные лигатуры/диграфы — заменяются ДО посимвольного разбора.
const LIGATURES: [RegExp, string][] = [
    [/ѿ/g, "ot"], [/Ѿ/g, "Ot"], // ѿ = лигатура "от"
    [/оу/g, "u"], [/Оу/g, "U"], [/ОУ/g, "U"], // диграф оук
    [/ꙋ/g, "u"], [/Ꙋ/g, "U"], // лигатура ук
]

const CHAR_MAP: Record<string, string> = {
    // Согласные — совпадают с совр. ISV-транслитерацией, см. lib/transliteration.ts
    "б": "b", "в": "v", "г": "g", "д": "d", "ж": "ž", "з": "z",
    "к": "k", "л": "l", "м": "m", "н": "n", "п": "p", "р": "r",
    "с": "s", "т": "t", "ф": "f", "х": "h", "ц": "c", "ч": "č", "ш": "š",
    "щ": "šč", // др.-рус.: /šč/; в старослав.-южном соответствии — št (см. правило №2)
    "ѕ": "dz", // дзело, редко

    // Гласные
    "а": "a", "е": "e", "и": "i", "і": "i", "о": "o", "у": "u", "ы": "y", "э": "e",
    "ꙇ": "i", // "иотированное и" / decimal I (U+A647) — в старослав. рукописях вариант "и"

    // Еры и ять — оставляем буквально, это не орфография ISV, а научная нотация
    "ъ": "ъ", "ь": "ь", "ѣ": "ě",

    // Носовые (юсы)
    "ѧ": "ę", "ѫ": "ǫ", "ѩ": "ję", "ѭ": "jǫ",

    // Прочие историч. буквы
    "ѡ": "o", // омега, стилистич. вариант о (часто в грецизмах/приставках)
    "ѳ": "f", // фита — греч. θ, в вост.-слав. произношении слилась с ф
    "ѵ": "i", // ижица — греч. υ, по умолчанию как i (менее уверенно, редкая буква)
    "й": "j",
    "ꙗ": "ja", // йотированное а, в основном старослав.
    "ѯ": "ks", "ѱ": "ps", // грецизмы, редко
}

// Йотированные гласные — после i/j пишем нейотированный вариант, иначе j+гласная
// (та же логика, что в lib/transliteration.ts::etymCyrToEtymLat)
const IOTATED: Record<string, [string, string]> = {
    "я": ["ja", "a"], "ю": ["ju", "u"], "ё": ["jo", "o"], "є": ["je", "e"],
}

/**
 * Транслитерирует слово/лемму из палеографической кириллицы (старослав. или
 * др.-вост.-слав. корпусов) в научную латиницу. Не резолвит числовые титла,
 * не восстанавливает выносные буквы — принимает уже развёрнутый (не сокращённый)
 * текст, как его отдают CoNLL-U FORM/LEMMA поля UD-трибанков.
 */
export function transliterateHistoricalCyrillic(text: string): string {
    if (!text) return ""

    let word = text.replace(COMBINING_TITLO, "")
    for (const [re, repl] of LIGATURES) word = word.replace(re, repl)

    const lower = word.toLowerCase()
    let mapped = ""
    for (let i = 0; i < lower.length; i++) {
        const ch = lower[i]
        if (IOTATED[ch]) {
            const prev = mapped.length > 0 ? mapped[mapped.length - 1] : ""
            mapped += (prev === "i" || prev === "j") ? IOTATED[ch][1] : IOTATED[ch][0]
            continue
        }
        mapped += CHAR_MAP[ch] ?? ch
    }

    return mapped
}
